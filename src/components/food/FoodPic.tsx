export function foodEmoji(name: string) {
  const s = name.toLowerCase();
  return EMOJI.find(([re]) => re.test(s))?.[1] ?? "🍽️";
}

/** Картинка продукта или блюда; нет картинки или не загрузилась — значок. */
export function FoodPic({ src, name, size = 44 }: { src?: string | null; name: string; size?: number }) {
  const [broken, setBroken] = useState<string | null>(null);
  const ok = src && broken !== src;
  return (
    <span
      className="flex shrink-0 items-center justify-center overflow-hidden rounded-2xl"
      style={{ width: size, height: size, background: "var(--surface-2)", fontSize: size * 0.5 }}
      aria-hidden
    >
      {ok ? (
        // eslint-disable-next-line @next/next/no-img-element
        <img src={src} alt="" loading="lazy" className="h-full w-full object-cover" onError={() => setBroken(src)} />
      ) : (
        foodEmoji(name)
      )}
    </span>
  );
}
