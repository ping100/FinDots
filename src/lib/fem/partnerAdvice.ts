/** Детерминированная «случайная» подборка на день: каждый день — своя. */
function pick<T>(list: T[], n: number, seed: number): T[] {
  if (list.length <= n) return list;
  const out: T[] = [];
  const pool = [...list];
  let x = seed;
  while (out.length < n && pool.length) {
    x = (x * 9301 + 49297) % 233280;
    out.push(pool.splice(x % pool.length, 1)[0]);
  }
  return out;
}

/** Без повторов по смыслу: пропускаем совет с общим словом из уже взятых. */
function uniq(list: string[], max: number): string[] {
  const words = (t: string) => new Set(t.toLowerCase().replace(/[^а-яё ]/g, " ").split(/\s+/).filter((w) => w.length >= 5));
  const out: string[] = [];
  for (const t of list) {
    const w = words(t);
    if (out.some((o) => [...words(o)].some((x) => w.has(x)))) continue;
    out.push(t);
    if (out.length === max) break;
  }
  return out;
}

const cap = (t: string) => t[0].toUpperCase() + t.slice(1);

export interface PartnerAdvice {
  understand: string[];
  soon: string[];
  todo: string[];
  notTodo: string[];
  say: string[];
}

export function adviceFor({
  phase,
  info,
  mood,
  symptoms,
  goal,
  today,
}: {
  phase: Phase;
  info: CycleInfo;
  mood: string | null;
  symptoms: string[];
  goal: Goal | null;
  today: string;
}): PartnerAdvice {
  const seed = Number(today.replace(/-/g, "")) % 100000;
  const conceive = goal === "conceive";
  const real = symptoms.filter((s) => s !== "ok");
  const moodTip = mood ? MOOD[mood] : null;
  const gentle = (!!mood && LOW_MOODS.has(mood)) || real.some((s) => PAIN.has(s));
  const soft = (list: string[]) => (gentle ? list.filter((t) => !ACTIVE.test(t)) : list);

  // Что скоро: заранее, чтобы успеть подготовиться.
  const soon: string[] = [];
  if (!info.current && info.late === 0 && info.daysToNext != null && info.daysToNext >= 1 && info.daysToNext <= 3) {
    soon.push(
      info.daysToNext === 1
        ? "Месячные, скорее всего, завтра — запаситесь вкусным и грелкой"
        : `Месячные примерно через ${info.daysToNext} дня — самое время быть внимательнее`,
    );
  }
  if (info.current && (info.cycleDay ?? 0) <= 2) soon.push("Первые дни месячных обычно самые тяжёлые — будьте рядом");
  if (info.fertileStart && !info.current) {
    const d = Math.round((Date.parse(info.fertileStart) - Date.parse(today)) / 86400000);
    if (d >= 1 && d <= 2) soon.push(d === 1 ? "Завтра начинаются фертильные дни" : "Через 2 дня начинаются фертильные дни");
  }
  if (info.ovulation && addDays(today, 1) === info.ovulation) soon.push("Завтра, по прогнозу, овуляция — пик цикла");

  const todo = uniq(
    [
      ...real.map((s) => CARE[s]).filter(Boolean).map(cap),
      ...(moodTip ? [moodTip[0]] : []),
      ...(conceive && (phase === "fertile" || phase === "ovulation") ? ["Лучшие дни для зачатия — побудьте вместе"] : []),
      ...pick(soft(DO[phase]), 4, seed),
      ...(gentle ? ["Спросите, чего ей сейчас хочется, — и сделайте"] : []),
    ],
    4,
  );
  const notTodo = uniq(
    [
      ...real.map((s) => SYMPTOM_DONT[s]).filter(Boolean),
      ...(moodTip?.[1] ? [moodTip[1]] : []),
      ...pick(
        DONT[phase].filter((t) => !(conceive && t.includes("защит")) && !(gentle && t.includes("отменяйте планы"))),
        3,
        seed + 7,
      ),
      ...(conceive ? ["Не давите разговорами о беременности"] : []),
    ],
    4,
  );
  return {
    understand: pick(UNDERSTAND[phase], 2, seed + 3),
    soon,
    todo,
    notTodo,
    say: pick(gentle ? GENTLE_SAY : SAY[phase], 2, seed + 11),
  };
}
