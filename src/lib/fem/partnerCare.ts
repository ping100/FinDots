/** Его оценки советов и галочки — хранятся в fem_shares.partner_state. */
export interface PartnerState {
  /** Текст совета → 1 «помогло» / −1 «не то». */
  votes?: Record<string, number>;
  /** Задания недели: неделя (понедельник) и выполненные. */
  week?: { key: string; done: string[] };
  /** Список «подготовиться заранее»: к какой дате и что уже есть. */
  prep?: { key: string; done: string[] };
}

/** Детерминированная «случайная» подборка: каждый день своя. */
export function seeded<T>(list: T[], n: number, seed: number): T[] {
  if (list.length <= n) return [...list];
  const out: T[] = [];
  const pool = [...list];
  let x = Math.abs(seed) % 233280;
  while (out.length < n && pool.length) {
    x = (x * 9301 + 49297) % 233280;
    out.push(pool.splice(x % pool.length, 1)[0]);
  }
  return out;
}

export const daySeed = (day: string) => Number(day.replace(/-/g, "")) % 100000;

