/** Советы из того, что она сама написала. Пусто — советы как раньше. */
export function likesTips(phase: Phase, likes: Likes | undefined): string[] {
  const l = likes ?? {};
  const out: string[] = [];
  const v = (k: string) => l[k]?.trim();
  const low = phase === "period" || phase === "luteal" || phase === "late";
  const bright = phase === "follicular" || phase === "fertile" || phase === "ovulation";
  if (v("sweet") && low) out.push(`Купите ей сладкое, которое она любит: ${v("sweet")}`);
  if (v("pain") && (phase === "period" || phase === "luteal")) out.push(`Проверьте, что дома есть то, что ей помогает: ${v("pain")}`);
  if (v("drink")) out.push(`Принесите её любимый напиток: ${v("drink")}`);
  if (v("food") && phase !== "ovulation") out.push(`Закажите или приготовьте её любимое: ${v("food")}`);
  if (v("flowers") && bright) out.push(`Подарите цветы, которые она любит: ${v("flowers")}`);
  if (v("joy")) out.push(`Порадуйте её тем, что она любит: ${v("joy")}`);
  return out;
}

/** «Не люблю» — в «чего не делать». */
export function dislikeTip(likes: Likes | undefined): string | null {
  const no = likes?.no?.trim();
  return no ? `Не покупайте и не дарите то, что она не любит: ${no}` : null;
}

// ───────────────────────────── подготовиться заранее ─────────────────────────────

export interface Prep {
  /** К какой дате список: по ней же помнятся галочки. */
  key: string;
  title: string;
  items: string[];
}

const plural = (n: number, one: string, few: string, many: string) => {
  const m10 = n % 10;
  const m100 = n % 100;
  return m10 === 1 && m100 !== 11 ? one : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? few : many;
};

export function prepFor(info: CycleInfo, likes: Likes | undefined, today: string): Prep | null {
  const l = likes ?? {};
  const v = (k: string) => l[k]?.trim();
  if (!info.current && info.late === 0 && info.nextStart && info.daysToNext != null && info.daysToNext >= 1 && info.daysToNext <= 4) {
    const n = info.daysToNext;
    return {
      key: `p:${info.nextStart}`,
      title: n === 1 ? "Завтра, скорее всего, начнутся месячные" : `Через ${n} ${plural(n, "день", "дня", "дней")} месячные`,
      items: [
        v("pain") ? `Что ей помогает при боли: ${v("pain")}` : "Грелка и обезболивающее, которое она обычно пьёт",
        v("sweet") ? `Сладкое: ${v("sweet")}` : "Что-нибудь сладкое: шоколад или её любимый десерт",
        v("drink") ? `Напиток: ${v("drink")}` : "Травяной чай или какао",
        "Спросите, хватает ли средств гигиены, и предложите купить",
        v("food") ? `Ужин на первый вечер: ${v("food")}` : "Продумайте простой ужин на первый вечер",
        "Не ставьте на первые два вечера важных дел",
      ],
    };
  }
  if (info.fertileStart && !info.current && info.late === 0) {
    const d = Math.round((Date.parse(info.fertileStart) - Date.parse(today)) / 86400000);
    if (d >= 1 && d <= 3) {
      return {
        key: `f:${info.fertileStart}`,
        title: d === 1 ? "С завтрашнего дня у неё лучшие дни цикла" : `Через ${d} ${plural(d, "день", "дня", "дней")} у неё лучшие дни цикла`,
        items: [
          "Запланируйте свидание на эти дни",
          "Забронируйте столик или билеты заранее",
          v("flowers") ? `Цветы: ${v("flowers")}` : "Цветы без повода",
          "Придумайте, куда вы давно хотели сходить",
        ],
      };
    }
  }
  return null;
}

