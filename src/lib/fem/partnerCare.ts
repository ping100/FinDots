/** Понедельник этой недели — ключ недели. */
export function weekKey(day: string): string {
  const d = new Date(`${day}T12:00:00`);
  const shift = (d.getDay() + 6) % 7;
  return addDays(day, -shift);
}

export function weekTasks(day: string): string[] {
  return seeded(WEEK_TASKS, 6, daySeed(weekKey(day)) + 41);
}

