/** О чём совет — чтобы «помогло» подтягивало похожие. */
const TAG_RULES: [string, RegExp][] = [
  ["food", /вкусн|еду|еда|ужин|завтрак|закаж|приготов|чай|какао|шоколад|десерт|фрукт|перекус|кофе|сладк/i],
  ["care", /грелк|плед|массаж|ванн|отдых|тёпл|тепл|выспат|тишин|полежим|уют/i],
  ["date", /свидан|прогулк|кино|сходите|выбер|поездк|ресторан|кафе|выходны|вдвоём|вдвоем|куда-нибудь/i],
  ["words", /скажите|комплимент|напомните|напишите|спросите|выслушайте|похвалите|поблагодарите|«/i],
  ["help", /дела|по дому|на себя|уборк|посуд|продукт|магазин|покупк/i],
  ["touch", /обним|поцел|за руку|массаж/i],
  ["gift", /сюрприз|цвет|подар|записк|открытк|мелоч/i],
  ["space", /одной|пространств|не трогайте|не нагружайте/i],
];

export function tagsOf(text: string): string[] {
  return TAG_RULES.filter(([, re]) => re.test(text)).map(([t]) => t);
}

/** Вес совета по его оценкам: «помогло» похожему +, «не то» −. */
export function weigher(votes: Record<string, number> | undefined) {
  const score = new Map<string, number>();
  for (const [text, v] of Object.entries(votes ?? {})) for (const t of tagsOf(text)) score.set(t, (score.get(t) ?? 0) + v);
  return (text: string) => {
    if (votes?.[text] === -1) return -99;
    const w = tagsOf(text).reduce((sum, t) => sum + (score.get(t) ?? 0), 0);
    return Math.max(-3, Math.min(3, w)) + (votes?.[text] === 1 ? 1 : 0);
  };
}

/** Подборка на день с учётом оценок: понравившееся чаще, «не то» никогда. */
export function pickWeighted(list: string[], n: number, seed: number, votes?: Record<string, number>): string[] {
  const weight = weigher(votes);
  let x = Math.abs(seed) % 233280;
  return list
    .map((text) => {
      x = (x * 9301 + 49297) % 233280;
      return { text, rank: x / 233280 + 0.3 * weight(text) };
    })
    .filter((r) => r.rank > -10)
    .sort((a, b) => b.rank - a.rank)
    .slice(0, n)
    .map((r) => r.text);
}

