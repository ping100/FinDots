/**
 * Куда можно уводить после входа.
 *
 * Адрес приходит из ссылки, а её может подсунуть кто угодно. Без проверки
 * «//evil.example» склеилось бы с нашим доменом в ссылку на чужой сайт — и
 * человек, вошедший у нас, оказался бы там, доверяя адресу, с которого
 * пришёл. Поэтому пускаем только свои пути: одна косая черта в начале и
 * ни одной сразу за ней. Обратная косая — тоже нельзя: браузер читает
 * «/\evil.example» как «//evil.example».
 */
export function safeNext(value: string | null | undefined): string {
  if (!value || !value.startsWith("/") || value.startsWith("//")) return "/";
  if (/[\\\u0000-\u001f]/.test(value)) return "/";
  return value;
}
