-- Регулярный платёж — свойство категории расхода, а не долга.
--
-- Раньше аренду и подписки предлагалось заводить как «долг — я должен» с
-- галочкой «ежемесячный». Это неверно по сути: у подписки нет остатка
-- задолженности, и оплата подписки — обычная трата, а не погашение долга.
-- В той модели баланс такого «долга» уходил в минус с каждым платежом.
--
-- Теперь у категории расхода есть ожидаемая сумма и число месяца. Платёж
-- записывается как обычная трата в эту категорию, а «можно тратить сегодня»
-- держит неоплаченный остаток в стороне от свободных денег.
--
-- У кредитов и займов ежемесячный платёж остаётся на кошельке-долге: там
-- он гасит тело долга, и это другая история.

alter table public.categories
  add column planned_amount numeric(14, 2) check (planned_amount is null or planned_amount > 0),
  add column due_day int check (due_day is null or (due_day between 1 and 31));
