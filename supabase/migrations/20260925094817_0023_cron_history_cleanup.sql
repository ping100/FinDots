-- Проверка напоминаний идёт раз в минуту, и планировщик пишет о каждом
-- запуске строку в журнал — 1440 строк в сутки. Неделю храним на случай
-- разбора, остальное каждую ночь убираем, чтобы база не пухла.
select cron.schedule(
  'purge-cron-history',
  '15 3 * * *',
  $$delete from cron.job_run_details where end_time < now() - interval '7 days'$$
);
