-- Один отзыв на человека, общий для обоих приложений.
--
-- ReviewRow рендерится и в money/settings, и в tasks/settings — раньше
-- это позволяло оставить по отзыву из каждого, и после отправки форма
-- в другом приложении выглядела пустой, будто отзыв пропал. Уникальность
-- по user_id делает это физически невозможным: строка одна, оба
-- приложения читают и показывают её.

alter table public.reviews add constraint reviews_user_id_key unique (user_id);
