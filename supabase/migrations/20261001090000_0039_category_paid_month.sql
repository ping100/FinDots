-- «Уже оплачено» для ежемесячных платежей (категории с planned_amount).
--
-- Обязательства в DailyAllowance считаются по фактическим операциям-тратам
-- в категории за месяц — если человек заплатил вне приложения (или занёс
-- трату позже), платёж до этого момента считается «ещё впереди» и зря
-- уменьшает «можно тратить сегодня». paid_month хранит месяц (первое
-- число), за который отметили «уже оплачено» вручную — следующий месяц
-- само поле не трогает, и платёж снова встаёт в обязательства, как обычно.

alter table public.categories add column paid_month date;
